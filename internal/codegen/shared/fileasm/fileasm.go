// Package fileasm assembles generated Go source files: the DO-NOT-EDIT header,
// build tag, package clause, grouped imports, and body — then formats the result
// with go/format. Every emitter funnels file output through Assemble so scaffold
// changes happen in exactly one place.
package fileasm

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// File is one Go source file awaiting assembly.
type File struct {
	// PackageName is the package clause name.
	PackageName string
	// BuildTag is the //go:build expression.
	BuildTag string
	// Imports maps alias → import path. Aliases equal to the path's last element
	// are emitted without an explicit alias.
	Imports map[string]string
	// Body is the file content below the imports.
	Body string
}

// Header marks files this module's generator owns; the emitter only ever prunes
// or overwrites files that carry it, so a hand-written file in the output tree is
// never touched.
const Header = "// Code generated by go-bindings-windowsappsdk-codegen. DO NOT EDIT."

// GeneratedBuildTag is the //go:build constraint every generated file carries.
//
// amd64 only. Struct layouts follow the 64-bit LLP64 model that Windows amd64 and
// arm64 share, but the CALLING CONVENTIONS diverge where floats are concerned,
// and the divergence is in Go's runtime rather than in anything this generator
// controls:
//
//   - runtime/internal/syscall's asm_windows_amd64.s mirrors each of the first
//     four argument words into XMM0-XMM3 before the call and stores XMM0 back as
//     the second result, so floats and by-value aggregates cross
//     syscall.SyscallN intact.
//   - asm_windows_arm64.s loads only R0-R7 and never touches V0-V7 — it still
//     carries a "TODO(rsc) floating point like amd64" note. On AArch64/Windows a
//     double is passed in V0 and a homogeneous float aggregate in V0-V3, so
//     every such argument would be silently corrupted.
//
// XAML's surface is unusually exposed to this. Opacity, Width, Height and
// FontSize are doubles; Thickness, CornerRadius, Point and Rect are all-float
// aggregates; Margin and Padding are on nearly every element. Emitting for arm64
// would mean shipping code that miscompiles the most-used members in the library,
// so the architecture is excluded until Go copies the arguments across. 386 stays
// excluded for the older reason: 32-bit pointers and distinct layouts.
const GeneratedBuildTag = "windows && amd64"

// Assemble renders and gofmts the file.
func Assemble(file File) ([]byte, error) {
	var buffer bytes.Buffer
	buffer.WriteString(Header + "\n")
	fmt.Fprintf(&buffer, "\n//go:build %s\n\n", file.BuildTag)
	fmt.Fprintf(&buffer, "package %s\n\n", file.PackageName)
	writeImports(&buffer, file.Imports)
	buffer.WriteString(file.Body)

	formatted, err := format.Source(buffer.Bytes())
	if err != nil {
		return nil, fmt.Errorf("fileasm: generated %s does not parse: %w", file.PackageName, err)
	}
	return formatted, nil
}

// writeImports emits the import block in two groups: standard library, then
// everything else (matching goimports grouping).
func writeImports(buffer *bytes.Buffer, imports map[string]string) {
	if len(imports) == 0 {
		return
	}
	var stdlib, external []string
	for alias, path := range imports {
		line := fmt.Sprintf("%s %q", alias, path)
		if lastSegment(path) == alias {
			line = fmt.Sprintf("%q", path)
		}
		// A dot in the first segment means a module path; the standard library
		// has none.
		if strings.Contains(path, ".") {
			external = append(external, line)
		} else {
			stdlib = append(stdlib, line)
		}
	}
	sort.Strings(stdlib)
	sort.Strings(external)

	buffer.WriteString("import (\n")
	for _, line := range stdlib {
		fmt.Fprintf(buffer, "\t%s\n", line)
	}
	if len(stdlib) > 0 && len(external) > 0 {
		buffer.WriteString("\n")
	}
	for _, line := range external {
		fmt.Fprintf(buffer, "\t%s\n", line)
	}
	buffer.WriteString(")\n\n")
}

func lastSegment(path string) string {
	if i := strings.LastIndex(path, "/"); i >= 0 {
		return path[i+1:]
	}
	return path
}

// WriteGoFile assembles the file and writes it to path, creating parent
// directories as needed.
func WriteGoFile(path string, file File) error {
	formatted, err := Assemble(file)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("fileasm: %w", err)
	}
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		return fmt.Errorf("fileasm: %w", err)
	}
	return nil
}
